"""상대역 대사에 섞인 명백한 평가·진행 안내를 걸러낸다. 업무상 평가는 허용한다."""
import re

_META_SPEECH = re.compile(
    r"평가자로서|평가자\s*(?:역할|입장)|채점\s*(?:기준|결과|하겠|해\s*드)|"
    r"(?:이|이번|현재|다음)\s*(?:시뮬레이션|시나리오|역할극|연습)\s*(?:은|는|의|에서|를|로)|"
    r"(?:대화|응답|답변|의사소통|소통\s*능력).{0,15}(?:점수|채점|평가하|평가해|평가할|평가받)|"
    r"(?:연습|훈련)\s*(?:목표|목적|항목|기준|단계|결과)|"
    r"(?:당신|사용자|참여자)의?\s*.{0,10}(?:능력|답변|대화).{0,10}(?:평가|채점)|"
    r"(?<![가-힣])평가\s*(?:리포트|점수)|"
    r"(?:다음|이번)\s*(?:막|턴|단계)\s*(?:으로|에서는|로|로\s*넘어)|"
    r"(?:시스템|개발자)\s*프롬프트|(?:AI|인공지능)\s*(?:로서|모델|평가자)|"
    r"(?:좋은|훌륭한|올바른|적절한|모범)\s*(?:답변|대응)(?:입니다|이에요|이었|이네요|예시)|"
    r"(?:점수를|가점을)\s*(?:드리|주겠|받으)|\b(?:rubric|beat_goal|last_case)\b",
    re.IGNORECASE,
)


def is_role_drift(text: str) -> bool:
    return bool(_META_SPEECH.search(text or ""))
